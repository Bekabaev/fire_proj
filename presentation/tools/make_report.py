def cell_fmt(c, w, head, center):
    tcPr = c._tc.get_or_add_tcPr()
    for tag in ("w:tcW",):
        e = tcPr.find(qn(tag))
        if e is None:
            e = OxmlElement(tag); tcPr.append(e)
        e.set(qn("w:w"), str(w)); e.set(qn("w:type"), "dxa")
    b = OxmlElement("w:tcBorders")
    for side in ("top", "left", "bottom", "right"):
        x = OxmlElement(f"w:{side}"); x.set(qn("w:val"), "single"); x.set(qn("w:sz"), "4"); x.set(qn("w:space"), "0"); x.set(qn("w:color"), "D9D9D9")
        b.append(x)
    tcPr.append(b)
    shd = OxmlElement("w:shd"); shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto"); shd.set(qn("w:fill"), "E9ECEE" if head else "FFFFFF")
    tcPr.append(shd)
    mar = OxmlElement("w:tcMar")
    for side, v in (("top", 80), ("left", 90), ("bottom", 80), ("right", 90)):
        x = OxmlElement(f"w:{side}"); x.set(qn("w:w"), str(v)); x.set(qn("w:type"), "dxa"); mar.append(x)
    tcPr.append(mar)
    va = OxmlElement("w:vAlign"); va.set(qn("w:val"), "center"); tcPr.append(va)
    p = c.paragraphs[0]; pf = p.paragraph_format; pf.space_after = Pt(0); pf.line_spacing = 1.05
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.LEFT
    if head:
        pf.keep_with_next = True
    for r in p.runs:
        r.font.size = Pt(10.5); r.bold = head


def table(title, rows, widths_cm, center_from=1):
    """rows[0] - заголовок. Колонки с индексом >= center_from выравниваются по центру (числа)."""
    global n_tab
    n_tab += 1; caption(f"Таблица {n_tab}. {title}")
    t = d.add_table(rows=len(rows), cols=len(rows[0]))
    tblPr = t._tbl.tblPr
    lay = OxmlElement("w:tblLayout"); lay.set(qn("w:type"), "fixed"); tblPr.append(lay)
    ws = [int(w / 2.54 * 1440) for w in widths_cm]
    grid = t._tbl.tblGrid
    for gc, w in zip(grid.findall(qn("w:gridCol")), ws):
        gc.set(qn("w:w"), str(w))
    for i, r in enumerate(rows):
        tr = t.rows[i]._tr; trPr = tr.get_or_add_trPr()
        trPr.append(OxmlElement("w:cantSplit"))
        if i == 0:
            trPr.append(OxmlElement("w:tblHeader"))
        for j, v in enumerate(r):
            c = t.cell(i, j); c.text = str(v)
            cell_fmt(c, ws[j], i == 0, j >= center_from and i > 0)
    para("", after=2)
    return t


