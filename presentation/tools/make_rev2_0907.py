notes(s, "Один пожар, три модели: 6 сентября 2026 года, Костанайская область. Факт — гарь по снимку Sentinel-2: узкая полоса 11 квадратных "
         "километров на север-северо-запад от старта. Слева физика — моделирование fires.kz: направление верное, но эллипс 65 квадратных "
         "километров, F1 0,28. В середине нейросеть: 9,8 квадратных километра, почти точно по площади, F1 0,31. Справа гибрид: 20 квадратных "
         "километров, захватывает и северную, и центральную часть гари, F1 0,34 — лучший из трёх.")

# ---------- слайд 25: гибрид по горизонтам ----------
s = S[24]
for idx, h in zip((0, 1, 2, 3), ("12h", "24h", "48h", "72h")):
    put(s, idx, os.path.join(F, f"hz_{h}.png"), crop_aspect=580 / 380)
for idx, h, f1_, true_, pred in ((5, 12, "0,11", "4,3", "4,5"), (7, 24, "0,40", "6,0", "7,8"), (9, 48, "0,37", "9,8", "13,3"), (11, 72, "0,38", "9,8", "16,8")):
    txt(s, idx, f"{h} ч · F1 {f1_}")
    txt(s, idx + 1, f"сгорело {true_} км²", f"прогноз {pred} км²")
txt(s, 13, "Пожар 7.09.2026, факт — термоточки VIIRS по горизонтам (по снимку Sentinel-2 на 72 ч гарь меньше — 3,3 км²). Масштаб модель держит, "
           "но растит пожар во все стороны от старта, а реальный рост шёл на северо-восток; к 48–72 ч площадь завышена.")
notes(s, "Тот же пожар 7 сентября 2026 года на четырёх горизонтах. Факт здесь — новые термоточки VIIRS за 12, 24, 48 и 72 часа, потому что снимки "
         "есть только на 72 часа. Тёмное — гарь на старте, красное — что сгорело, синее — прогноз. За первые сутки модель попадает в масштаб: "
         "4,5 против 4,3 и 7,8 против 6 квадратных километров, F1 до 0,40. Дальше пожар почти остановился, а модель продолжала его растить "
         "до 17 квадратных километров — та же слабость, что на всём тесте: на 48–72 часа площадь завышена.")

out = os.path.join(P, "pres_final_rev2.pptx")
prs.save(out); print("saved", out)
