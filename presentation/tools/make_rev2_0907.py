import os, io
from PIL import Image
from pptx import Presentation

P = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "presentation")
F = os.path.join(P, "fireskz_0907")
prs = Presentation(os.path.join(P, "pres_final_rev1.pptx"))
S = list(prs.slides)


def put(sl, idx, path, crop_aspect=None):
    sh = list(sl.shapes)[idx]; assert sh.shape_type == 13
    im = Image.open(path).convert("RGB")
    if crop_aspect:                                                    # обрезка по центру под пропорции рамки
        w, h = im.size; nh = int(round(w / crop_aspect)); top = (h - nh) // 2
        im = im.crop((0, top, w, top + nh))
    buf = io.BytesIO(); im.save(buf, "PNG"); buf.seek(0)
    _, rid = sl.part.get_or_add_image_part(buf)
    sh._element.blipFill.blip.rEmbed = rid


def txt(sl, idx, *paras):
    sh = list(sl.shapes)[idx]; tf = sh.text_frame
    ps = tf.paragraphs; assert len(ps) >= len(paras), (idx, len(ps))
    for p, t in zip(ps, paras):
        rs = p.runs; rs[0].text = t
        for r in rs[1:]:
            r.text = ""
    for p in ps[len(paras):]:
        for r in p.runs:
            r.text = ""


def notes(sl, t):
    sl.notes_slide.notes_text_frame.text = t


F6 = os.path.join(P, "fireskz_0906")                                   # самый удачный пример: 6.09.2026, Костанайская обл.
# ---------- слайд 15: физика = fires.kz ----------
s = S[14]
put(s, 1, os.path.join(F6, "phys_kz_s2.png"))
txt(s, 2, "Что выдаёт физика: моделирование fires.kz")
txt(s, 4, "одна термоточка (6.09.2026, 20:40 UTC, Костанайская обл., у Кумшика), топливо, рельеф и погода — расчёт сайта fires.kz")
txt(s, 5, "На выходе — контуры по шагам")
txt(s, 6, "от красного (начало) до синего (24-й шаг). Красная линия — что реально сгорело (снимок Sentinel-2), чёрное — гарь на старте.")
txt(s, 7, "Слабое место физики")
txt(s, 8, "направление верное — на северо-запад, но не знает, когда пожар остановится")
txt(s, 9, "65,0 км²")
txt(s, 10, "по fires.kz (на деле 11,3)")
txt(s, 11, "0,28")
notes(s, "Физику здесь показываем независимым расчётом — моделированием сайта fires.kz для пожара 6 сентября 2026 года в Костанайской области. "
         "Модель запускается от одной термоточки и растит огонь по ветру с юго-востока. Направление она угадала: реальная гарь — узкая полоса "
         "на север-северо-запад, и она лежит внутри эллипса. Но физика не знает, когда пожар остановится: 65 квадратных километров при реальных "
         "11, площадь завышена почти в 6 раз. Внутри нашего гибрида работает своя физическая модель FBP того же типа.")

# ---------- слайд 16: U-Net ----------
s = S[15]
put(s, 1, os.path.join(F6, "unet_P_s2.png"))
txt(s, 4, "для каждой клетки — шанс сгореть за 72 ч. Тёмно-синее — почти наверняка, чёрная линия — 50 %. Красный пунктир — что сгорело на деле (снимок Sentinel-2).")
txt(s, 9, "9,8 км²")
txt(s, 10, "за 72 ч при пороге 50 % (на деле 11,3)")
txt(s, 11, "0,31")
notes(s, "А это нейросеть на том же пожаре 6 сентября 2026 года. Она выдаёт вероятность сгореть за 72 часа. Площадь почти точная: 9,8 квадратных "
         "километра при реальных 11,3, и пятно вытянуто туда же, куда пошёл огонь, на север. Часть южного края гари она пропустила. F1 0,31 — "
         "выше, чем у моделирования fires.kz, 0,28, при площади в 6–7 раз меньше.")

# ---------- слайд 20: три модели ----------
s = S[19]
for idx, name in ((15, "cmp_kz_s2.png"), (16, "cmp_unet_s2.png"), (17, "cmp_hybrid_s2.png")):
    put(s, idx, os.path.join(F6, name))
