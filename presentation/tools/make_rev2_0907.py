import os, io
from PIL import Image
from pptx import Presentation

P = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "presentation")
F = os.path.join(P, "fireskz_0907")
prs = Presentation(os.path.join(P, "pres_final_rev1.pptx"))
S = list(prs.slides)


def put(sl, idx, path, crop_aspect=None):
    sh = list(sl.shapes)[idx]; assert sh.shape_type == 13
    im = Image.open(path).convert("RGB")
    if crop_aspect:                                                    # обрезка по центру под пропорции рамки
        w, h = im.size; nh = int(round(w / crop_aspect)); top = (h - nh) // 2
        im = im.crop((0, top, w, top + nh))
    buf = io.BytesIO(); im.save(buf, "PNG"); buf.seek(0)
    _, rid = sl.part.get_or_add_image_part(buf)
    sh._element.blipFill.blip.rEmbed = rid


def txt(sl, idx, *paras):
    sh = list(sl.shapes)[idx]; tf = sh.text_frame
    ps = tf.paragraphs; assert len(ps) >= len(paras), (idx, len(ps))
    for p, t in zip(ps, paras):
        rs = p.runs; rs[0].text = t
        for r in rs[1:]:
            r.text = ""
    for p in ps[len(paras):]:
        for r in p.runs:
            r.text = ""


def notes(sl, t):
    sl.notes_slide.notes_text_frame.text = t


# ---------- слайд 15: физика = fires.kz ----------
s = S[14]
put(s, 1, os.path.join(F, "phys_kz_s2.png"))
txt(s, 2, "Что выдаёт физика: моделирование fires.kz")
txt(s, 4, "одна термоточка (7.09.2026, 22:01 UTC, Карагандинская обл.), топливо, рельеф и погода — расчёт сайта fires.kz")
txt(s, 5, "На выходе — контуры по шагам")
txt(s, 6, "от красного (начало) до синего (24-й шаг). Красная линия — что реально сгорело за 72 ч (снимок Sentinel-2), чёрное — гарь на старте.")
txt(s, 7, "Слабое место физики")
txt(s, 8, "не знает, погаснет ли пожар: эллипс ушёл по ветру на запад")
txt(s, 9, "68,5 км²")
txt(s, 10, "по fires.kz (на деле 3,3)")
txt(s, 11, "0,01")
notes(s, "Физику здесь показываем независимым расчётом — моделированием сайта fires.kz для пожара 7 сентября 2026 года в Карагандинской "
         "области. Модель запускается от одной термоточки и растит огонь по ветру: за 24 шага эллипс ушёл на запад и вырос до 68 квадратных "
         "километров. Реально, по снимку Sentinel-2 через трое суток, сгорело 3,3 квадратных километра, и к северо-востоку от старта. "
         "Физика не знает, что пожар скоро погаснет, поэтому площадь завышена в 20 раз. Внутри нашего гибрида работает своя физическая модель "
         "FBP того же типа.")

# ---------- слайд 16: U-Net ----------
s = S[15]
put(s, 1, os.path.join(F, "unet_P_s2.png"))
txt(s, 4, "для каждой клетки — шанс сгореть за 72 ч. Тёмно-синее — почти наверняка, чёрная линия — 50 %. Красный пунктир — что сгорело на деле (снимок Sentinel-2).")
